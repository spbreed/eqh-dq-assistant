def core_ddl() -> str:
    out = ["-- GENERATED by datagen/redshift_ddl.py from datagen/writer.py SILVER_TYPES. Do not edit by hand.",
           "-- Column order matches the silver Parquet files (COPY maps Parquet columns by position).", ""]
    for entity, types in SILVER_TYPES.items():
        cols = [f"    {c} {WIDE.get(c, RS_TYPES[t])}" for c, t in types.items()] + ["    ingest_date date"]
        key = KEYS.get(entity)
        out.append(f"CREATE TABLE IF NOT EXISTS core.{entity} (\n" + ",\n".join(cols) + "\n)"
                   + (f" DISTKEY({key})" if key else " DISTSTYLE AUTO") + " SORTKEY(ingest_date);")
    out.append("")
    out += comments_sql()
    return "\n".join(out) + "\n"


GENERIC = {"payer_code": "payer code (PAYER_XXn)", "state": "state", "ingest_date": "load date",
           "member_id": "member id", "practice_id": "practice", "service_date": "DOS"}


def column_comments() -> dict[tuple[str, str], str]:
    """Hand-written comments plus generic ones on every other table, to land near 40% column coverage."""
    out = dict(COLUMN_COMMENTS)
    for i, (t, types) in enumerate(SILVER_TYPES.items()):
        if i % 2:
            continue
        for col in list(types) + ["ingest_date"]:
            if col in GENERIC:
                out.setdefault((t, col), GENERIC[col])
    return out


def _q(s: str) -> str:
    return s.replace("'", "''")


def comments_sql(entity: str | None = None) -> list[str]:
    out = []
    for t, c in TABLE_COMMENTS.items():
        if entity in (None, t):
            out.append(f"COMMENT ON TABLE core.{t} IS '{_q(c)}';")
    for (t, col), c in column_comments().items():
        if entity in (None, t):
            out.append(f"COMMENT ON COLUMN core.{t}.{col} IS '{_q(c)}';")
    return out


